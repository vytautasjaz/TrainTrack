import { SessionType, WorkoutType } from '@prisma/client'
import type { CandidateWorkout } from '@/lib/coach-engine/types'
import { alignCandidateWithStructure } from '@/lib/coach-engine/session-copy'
import type {
  Segment,
  Target,
  WorkoutBlock,
  WorkoutIncludeItem,
  WorkoutStructure,
} from '@/lib/workout-builder/types'

function bid(workoutId: string, key: string) {
  return `${workoutId}__${key}`
}

function seg(
  mode: Segment['mode'],
  value: number,
  unit: Segment['unit'],
  description?: string,
): Segment {
  return { mode, value, unit, description }
}

function continuous(args: {
  id: string
  order: number
  name: string
  durationType: 'time' | 'distance'
  time?: number
  distance?: number
  distanceUnit?: 'km' | 'm'
  targets?: Target[]
  notes?: string
}): WorkoutBlock {
  return {
    id: args.id,
    order: args.order,
    type: 'CONTINUOUS',
    name: args.name,
    durationType: args.durationType,
    time: args.time,
    distance: args.distance,
    distanceUnit: args.distanceUnit,
    targets: args.targets,
    notes: args.notes,
  }
}

function interval(args: {
  id: string
  order: number
  name: string
  repetitions: number
  work: Segment
  recovery?: Segment
  targets?: Target[]
  notes?: string
}): WorkoutBlock {
  return {
    id: args.id,
    order: args.order,
    type: 'INTERVAL',
    name: args.name,
    repetitions: args.repetitions,
    work: args.work,
    recovery: args.recovery,
    targets: args.targets,
    notes: args.notes,
  }
}

function progressive(args: {
  id: string
  order: number
  name: string
  durationType: 'time' | 'distance'
  time?: number
  distance?: number
  distanceUnit?: 'km' | 'm'
  start: Target
  end: Target
  stepEvery: Segment
  notes?: string
}): WorkoutBlock {
  return {
    id: args.id,
    order: args.order,
    type: 'PROGRESSIVE',
    name: args.name,
    durationType: args.durationType,
    time: args.time,
    distance: args.distance,
    distanceUnit: args.distanceUnit,
    startIntensity: args.start,
    endIntensity: args.end,
    stepEvery: {
      mode: args.stepEvery.mode,
      value: args.stepEvery.value,
      unit: args.stepEvery.unit,
    },
    targets: [args.start],
    notes: args.notes,
  }
}

function struct(
  warmup: WorkoutBlock[],
  mainSet: WorkoutBlock[],
  cooldown: WorkoutBlock[],
  extras?: {
    coachNotes?: string
    includeItems?: WorkoutIncludeItem[]
    /** Ignored — card copy is always derived from blocks. */
    essence?: string
  },
): WorkoutStructure {
  // Do not seed cardSummary.essence overrides. Stale free-text essences
  // (and adaptation rewrites that only patch rep counts) made subtitle,
  // card summary, and real structure disagree in the builder.
  return {
    warmup,
    mainSet,
    cooldown,
    coachNotes: extras?.coachNotes,
    includeItems: extras?.includeItems ?? [],
  }
}

function meta(
  partial: Omit<CandidateWorkout, 'structure' | 'swimStructure'> & {
    structure: WorkoutStructure
  },
): CandidateWorkout {
  // Builder structure is the source of truth for duration, distance, and copy.
  return alignCandidateWithStructure(partial)
}

